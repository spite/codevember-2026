const CASSETTE = ["###########", "#.........#", "#.##...##.#", "#.##...##.#", "#.........#", "###########"];

export const CELL = 6;
export const textWidth = (text) => text.length * CELL - 1;

function bitmap(ctx, rows, x, y) {
  rows.forEach((row, j) => {
    for (let i = 0; i < row.length; i++) if (row[i] === "#") ctx.fillRect(x + i, y + j, 1, 1);
  });
}
// Text at whole pixels; align "right" puts its right edge at x.
export function drawText(ctx, text, x, y, align = "left") {
  let cx = align === "right" ? x - textWidth(text) : x;
  for (const ch of text) {
    bitmap(ctx, G[ch] ?? G[" "], cx, y);
    cx += CELL;
  }
}
export function drawCassette(ctx, x, y) {
  bitmap(ctx, CASSETTE, x, y);
}
// A battery cell 11 x 5 with up to three bars.
export function drawBattery(ctx, x, y, bars) {
  bitmap(ctx, ["#########..", "#.......###", "#.......###", "#.......###", "#########.."], x, y);
  for (let k = 0; k < bars; k++) ctx.fillRect(x + 2 + k * 2, y + 1, 1, 3);
}
// Viewfinder brackets in the four corners.
export function drawCorners(ctx, W, H, inset, arm) {
  ctx.fillRect(inset, inset, arm, 1);
  ctx.fillRect(inset, inset, 1, arm);
  ctx.fillRect(W - inset - arm, inset, arm, 1);
  ctx.fillRect(W - inset - 1, inset, 1, arm);
  ctx.fillRect(inset, H - inset - 1, arm, 1);
  ctx.fillRect(inset, H - inset - arm, 1, arm);
  ctx.fillRect(W - inset - arm, H - inset - 1, arm, 1);
  ctx.fillRect(W - inset - 1, H - inset - arm, 1, arm);
}
